SELECT SIGLA, NOME AS 'NOME DO ESTADO' FROM ESTADOS

-- FILTRAR DE DADOS 
WHERE REGIAO = "SUL"

-- FILTRAR DADOS POR COMPARAÇÃO
SELECT NOME, REGIAO FROM ESTADOS
WHERE POPULACAO >= 10

-- FILTRAR DADOS POR COMPARAÇÃO E DEFINIR DO MENOR PARA O MAIOR E USANDO A PALAVRA RESERVADA (DESC) - DECRESCENTE
SELECT NOME, REGIAO, POPULACAO FROM ESTADOS
WHERE POPULACAO >= 10
ORDER BY POPULACAO

-- FILTRAR DADOS POR COMPARAÇÃO E DEFINIR DO MENOR PARA O MAIOR | DESC = ORDENAÇÃO DECRESCENTE
SELECT NOME, REGIAO, POPULACAO FROM ESTADOS
WHERE POPULACAO >= 10
ORDER BY POPULACAO DESC




